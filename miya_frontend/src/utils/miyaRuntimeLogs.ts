export type RuntimeCategory = 'memory' | 'execution' | 'connection'
export type RuntimeSeverity = 'all' | 'warning' | 'error'

export interface RuntimeAnchor {
  category: RuntimeCategory
  x: number
  y: number
  radius: number
}

export interface RuntimeLog {
  seq: number
  ts: string
  level: string
  name: string
  text: string
  category: RuntimeCategory
  historical: boolean
  receivedAt: number
}

export const RUNTIME_RINGS = [
  { id: 'memory', label: '记忆', english: 'MEMORY', x: 224, y: 145, radius: 112 },
  { id: 'execution', label: '运行记录', english: 'RUNTIME', x: 112, y: 306, radius: 76 },
  { id: 'connection', label: '感知与连接', english: 'PERCEPTION / LINK', x: 330, y: 294, radius: 66 },
] as const

// Strip terminal escapes before placing log content in SVG or plain-text details.
// eslint-disable-next-line no-control-regex, regexp/no-obscure-range
const ANSI_ESCAPE = /\u001B\[[0-?]*[ -/]*[@-~]/g
// eslint-disable-next-line no-control-regex
const CONTROL_CHARACTERS = /[\u0000-\u0008\v\f\u000E-\u001F\u007F]/g
const WARNING_LEVEL = /^(?:WARNING|ERROR|CRITICAL|ERR)$/
const ERROR_LEVEL = /^(?:ERROR|CRITICAL|ERR)$/
const QUERY_SEPARATOR = /\s+/
const ACCESS_MODULE = /^(?:uvicorn\.(?:access|error)|httpx|httpcore|watchfiles)(?:\.|$)/i
const WS_ACCESS = /WS 客户端(?:连接|断开)/
const API_ACCESS = /(?:GET|POST|OPTIONS)\s+\/?(?:api\/|health\b)/i
const GENERIC_MODULE = /^(?:stdout|stderr|root)$/i
const MEMORY_MODULE = /memory|recall|historian|cogniti|lifebook|knowledge|记忆|知识库/i
const CONNECTION_MODULE = /platform|onebot|telegram|discord|wechat|weixin|qqofficial|vision|percept|camera|speech|tts|voice|m[._-]?link|message|感知|视觉|语音|平台|消息收发/i
const CONNECTION_MESSAGE = /\[(?:TTS|WebChat|Vision|MLink)\]/i
const LOG_PREFIX = /^\[[^\]]+\]\s*(?:INFO|WARNING|ERROR|CRITICAL|DEBUG):\s*/
const WHITESPACE = /\s+/g

export function runtimeWarning(entry: RuntimeLog) {
  return WARNING_LEVEL.test(entry.level)
}

export function filterRuntimeLogs(entries: RuntimeLog[], query: string, severity: RuntimeSeverity) {
  const terms = query.trim().toLocaleLowerCase().split(QUERY_SEPARATOR).filter(Boolean)
  return entries.filter((entry) => {
    if (severity === 'warning' && !runtimeWarning(entry))
      return false
    if (severity === 'error' && !ERROR_LEVEL.test(entry.level))
      return false
    const searchable = `${entry.name}\n${entry.text}\n${entry.level}\n${entry.ts}`.toLocaleLowerCase()
    return terms.every(term => searchable.includes(term))
  })
}

// Reserve room for every category so a busy module cannot displace the others.
export function runtimeTelemetry(entries: RuntimeLog[]) {
  return RUNTIME_RINGS.flatMap(ring => entries.filter(entry => entry.category === ring.id).slice(-8))
    .sort((a, b) => a.seq - b.seq)
}

export function normalizeRuntimeLog(value: unknown, historical: boolean, receivedAt: number): RuntimeLog | null {
  if (!value || typeof value !== 'object')
    return null
  const entry = value as Record<string, unknown>
  if (!Number.isSafeInteger(entry.seq) || (entry.seq as number) <= 0
    || typeof entry.ts !== 'string' || !Number.isFinite(Date.parse(entry.ts))
    || typeof entry.name !== 'string' || typeof entry.level !== 'string' || typeof entry.text !== 'string') {
    return null
  }
  const name = entry.name.slice(0, 160)
  const text = entry.text.replace(ANSI_ESCAPE, '').replace(CONTROL_CHARACTERS, '').slice(0, 8000)
  const level = entry.level.slice(0, 20).toUpperCase()
  const warning = WARNING_LEVEL.test(level)
  // Access traffic generated by opening the observatory must not animate it.
  if (!warning && (entry.source === 'frontend' || name === 'Miya.DesktopFrontend'
    || ACCESS_MODULE.test(name)
    || (name === 'Miya.ManagementAPI' && WS_ACCESS.test(text))
    || API_ACCESS.test(text))) {
    return null
  }
  if (!text.trim())
    return null
  // Prefer the emitting module; message matching only supplements stdout/stderr.
  const generic = GENERIC_MODULE.test(name)
  const source = generic ? text : name
  let category: RuntimeCategory = 'execution'
  if (MEMORY_MODULE.test(source)) {
    category = 'memory'
  }
  else if (CONNECTION_MODULE.test(source)
    || CONNECTION_MESSAGE.test(text)) {
    category = 'connection'
  }
  return { seq: entry.seq as number, ts: entry.ts, level, name, text, category, historical, receivedAt }
}

export function runtimeExcerpt(entry: RuntimeLog | undefined, length = 54) {
  if (!entry)
    return ''
  const text = entry.text.replace(LOG_PREFIX, '').replace(WHITESPACE, ' ').trim()
  return text.length > length ? `${text.slice(0, length)}…` : text
}

export function reduceRuntimePayload(current: RuntimeLog[], cursor: number, value: unknown, now: number) {
  if (!value || typeof value !== 'object')
    return null
  const payload = value as Record<string, unknown>
  if (!['init', 'reset', 'logs'].includes(payload.type as string) || !Array.isArray(payload.entries))
    return null
  const replacement = payload.type !== 'logs'
  const entries = replacement ? [] : [...current]
  let nextCursor = replacement ? 0 : cursor
  const seen = new Set(entries.map(entry => entry.seq))
  const ordered = payload.entries.map(entry => normalizeRuntimeLog(entry, replacement || payload.historical === true, now)).filter((entry): entry is RuntimeLog => !!entry).sort((a, b) => a.seq - b.seq)
  for (const entry of ordered) {
    if (seen.has(entry.seq) || (!replacement && entry.seq <= cursor))
      continue
    entries.push(entry)
    seen.add(entry.seq)
    nextCursor = Math.max(nextCursor, entry.seq)
  }
  // Move the cursor past filtered traffic as well, so reconnect does not replay it.
  for (const raw of payload.entries) {
    if (raw && Number.isSafeInteger(raw.seq) && raw.seq > 0)
      nextCursor = Math.max(nextCursor, raw.seq)
  }
  if (Number.isSafeInteger(payload.latest_seq) && (payload.latest_seq as number) >= 0)
    nextCursor = Math.max(nextCursor, payload.latest_seq as number)
  const counts: Record<RuntimeCategory, number> = { memory: 0, execution: 0, connection: 0 }
  const bounded = entries.reverse().filter(entry => ++counts[entry.category] <= 160).reverse()
  return { entries: bounded, cursor: nextCursor }
}
